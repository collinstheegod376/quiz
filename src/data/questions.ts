// Helper: Retrieves real, authoritative questions for match play with smart fallbacks
export function getQuestionsForMatch(
  topicId: string,
  levelNumber: number,
  count: number
): Question[] {
  // 1. Direct matches for the exact topic and tier
  const directMatches = SEED_QUESTIONS.filter(
    (q) => q.topicId === topicId && q.levelNumber === levelNumber
  );

  // 2. Secondary matches from the same topic (any tier)
  const sameTopicOtherTiers = SEED_QUESTIONS.filter(
    (q) => q.topicId === topicId && q.levelNumber !== levelNumber
  );

  // Combine direct matches first, then same topic
  const pool: Question[] = [...directMatches];
  for (const q of sameTopicOtherTiers) {
    if (!pool.some((p) => p.id === q.id)) {
      pool.push(q);
    }
  }

  // 3. If still short of the requested count (e.g. for emerging topics), fill with other authentic questions
  if (pool.length < count) {
    const otherQuestions = SEED_QUESTIONS.filter((q) => q.topicId !== topicId);
    for (const q of otherQuestions) {
      if (!pool.some((p) => p.id === q.id)) {
        pool.push(q);
      }
      if (pool.length >= count) break;
    }
  }

  // Shuffle and slice to the requested count
  const shuffled = [...pool].sort(() => Math.random() - 0.5);
  return shuffled.slice(0, count);
}
